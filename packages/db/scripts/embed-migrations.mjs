// Copies drizzle-kit's SQL migrations (drizzle/) into src/migrations.generated.ts, so they ship
// inside the bundled API (apps/api is built with esbuild into dist/, with no migration folder).
// Run through `pnpm --filter @uposhom/db db:generate`; test/migrations.test.ts fails if the two
// ever disagree.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import console from 'node:console';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8'));

// drizzle-kit writes REFERENCES "public"."users". Dropping the schema name makes the SQL follow
// search_path, like A's migrations, so tests can run each in a schema of their own.
export const unqualify = (sql) => sql.replaceAll('"public".', '');

const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map((e) => ({
    id: e.tag,
    sql: unqualify(readFileSync(join(root, 'drizzle', `${e.tag}.sql`), 'utf8')),
  }));

const body =
  '// GENERATED by scripts/embed-migrations.mjs from drizzle/. Do not edit by hand.\n' +
  "import type { Migration } from './migrate.js';\n\n" +
  `export const DOMAIN_MIGRATIONS: Migration[] = ${JSON.stringify(migrations, null, 2)};\n`;

writeFileSync(join(root, 'src/migrations.generated.ts'), body);
console.log(`embedded ${migrations.length} migrations: ${migrations.map((m) => m.id).join(', ')}`);
